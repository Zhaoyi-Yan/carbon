"""Audit the separate 16-game Artemis historical stratum; never execute strategies.

Usage: python history.py HISTORY_INPUT CURRENT_OUTPUT OUTPUT [--archive]
CURRENT_OUTPUT must have been generated by explore.py and facts.py.
"""
import argparse
from collections import Counter
import gzip
import io
import json
from pathlib import Path
import tarfile

from explore import ARTEMIS, CURRENT_METADATA_SHA256, SOURCE, measure, sha
from facts import net_tree, opening, summary

HISTORY_SOURCE = '88717e63390fb8a3531c290b42bae2e01f5e9540'
HISTORY_METADATA_SHA256 = {
    'index.json': 'c5346e2eda9881b4d465a03fa4f404b16f08e8a63d3c18c6fb2bae29d98c8e69',
    'leaderboard.json': '70b3d8323add7675cffffb46d0b98081a307b0bb379743a6f3900c5a5b7935b8',
    'README.md': '1589791ed5a1119bca10f1202dd0e1d93ff693f58b6286cf709bf30093d6ba3f',
    'artemis-index.json': '7172b80e7b54843438e46b071395eefeccdba3b2c093b300beaf1c890de46148',
    'recovered-sha256.json': '2c93254fec9f8e3769bee96b1793a9dc0620134ea983867a4d8b9297b5bb1d25',
}
# These are ranks 1..6 in the current ddc3e6f snapshot, not the old ranking.
CURRENT_TOP6 = {
    ARTEMIS, '226891089ba7f54b198c8f8dc771dfc2',
    'dd1f117a64c676225f0c6333b1cdd1e7', '6b717fdd3d51a00f8874148b2aeb9b02',
    'a5140e5e2640fb6b85123a4fbbfad8d0', '152ef1e3d0da179472008974bdb8f706',
}
SAMPLE_COLUMNS = ['own_cash','opponent_cash','own_cargo','opponent_cargo',
                  'own_trees','opponent_trees','own_collectors','opponent_collectors',
                  'own_planters','opponent_planters']


def read_json(path):
    return json.loads(path.read_text())


def write_json(path, value, compact=False):
    options = dict(separators=(',', ':')) if compact else dict(indent=2)
    path.write_text(json.dumps(value, ensure_ascii=False, **options) + '\n')


def rows_for(games):
    return [(g, next(s for s in g['seats'] if s['id']==ARTEMIS),
             next(s for s in g['seats'] if s['id']!=ARTEMIS)) for g in games
            if any(s['id']==ARTEMIS for s in g['seats'])]


def role_code(first_recruit):
    if first_recruit is None:
        return None
    return ''.join({'RECCOLLECTOR':'C', 'RECPLANTER':'P'}.get(b['action'],'-')
                   for b in first_recruit['base_actions'])


def opening_counts(traces):
    first_records = [g['first_three_steps'][0]['sides'][0] for g in traces]
    return dict(games=len(traces),
                empty_first_action=sum(not x['actions'] for x in first_records),
                first_action_status=dict(Counter(x['status'] for x in first_records)),
                first_action_nonempty_info=sum(bool(x['info']) for x in first_records),
                first_action_remaining_overage=dict(Counter(str(x['remainingOverageTime']) for x in first_records)),
                first_recruit_state=dict(Counter(str(g['first_recruit_artemis']['replay_state']) for g in traces)))


def compact_game(row, trace):
    g,s,o = row
    samples = {}
    for t,a in s['samples'].items():
        b = o['samples'][t]
        samples[t] = [a['cash'],b['cash'],round(a['cargo'],6),round(b['cargo'],6),
                      a['trees'],b['trees'],a['collectors'],b['collectors'],a['planters'],b['planters']]
    observed_totals = {}
    for key in ('tree_income','tree_turns','plants','seizes','recruit_cost','plant_cost','seize_cost','terminal_cargo'):
        observed_totals[key] = [s['totals'].get(key,0),o['totals'].get(key,0)]
    return dict(match=g['match'],game=g['game'],file=g['file'],seed=g['seed'],
                layout_sha256=g['layout_sha256'],seat=s['seat'],opponent=o['id'],opponent_name=o['name'],
                opponent_is_current_top6=o['id'] in CURRENT_TOP6,
                margin=round(s['score']-o['score'],6),samples=samples,
                totals_own_opponent=observed_totals,net_tree_difference=net_tree(s)-net_tree(o),
                first_recruit=dict(own_state=trace['first_recruit_artemis']['replay_state'],
                                   own_roles=role_code(trace['first_recruit_artemis']),
                                   opponent_state=trace['first_recruit_opponent']['replay_state'],
                                   opponent_roles=role_code(trace['first_recruit_opponent'])))


def pack_history(snapshot, output, replay_files):
    names = sorted(set(replay_files) | {'index.json','leaderboard.json','README.md',
                   'artemis-index.json','provenance.json','recovered-sha256.json',
                   'source-manifest.jsonl.gz'})
    members = []
    package = output/'history_inputs.tar.gz'
    with package.open('wb') as raw:
        with gzip.GzipFile(filename='',fileobj=raw,mode='wb',mtime=0) as z:
            with tarfile.open(fileobj=z,mode='w|',format=tarfile.USTAR_FORMAT) as archive:
                for name in names:
                    data = (snapshot/name).read_bytes()
                    info = tarfile.TarInfo(name)
                    info.size=len(data);info.mode=0o644;info.mtime=0
                    archive.addfile(info,io.BytesIO(data))
                    members.append(dict(file=name,size=len(data),sha256=sha(data)))
    # Verify every member against its original byte stream, not just filenames.
    with tarfile.open(package,'r:gz') as archive:
        assert archive.getnames()==names
        for member in members:
            assert sha(archive.extractfile(member['file']).read())==member['sha256']
    record = dict(snapshot=HISTORY_SOURCE,file=package.name,size=package.stat().st_size,
                  sha256=sha(package.read_bytes()),members=members)
    write_json(output/'history_archive.json',record)
    return {k:v for k,v in record.items() if k!='members'}


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('history_input',type=Path)
    parser.add_argument('current_output',type=Path)
    parser.add_argument('output',type=Path)
    parser.add_argument('--archive',action='store_true')
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    for name,expected in HISTORY_METADATA_SHA256.items():
        actual=sha((args.history_input/name).read_bytes())
        if actual!=expected:
            raise ValueError(f'{name}: expected historical SHA256 {expected}, got {actual}')
    provenance=read_json(args.history_input/'provenance.json')
    assert provenance['source_commit']==HISTORY_SOURCE and provenance['strategy_id']==ARTEMIS
    current_manifest=read_json(args.current_output/'manifest.json')
    assert current_manifest['snapshot']==SOURCE
    assert current_manifest['index_sha256']==CURRENT_METADATA_SHA256['index.json']
    assert current_manifest['leaderboard_sha256']==CURRENT_METADATA_SHA256['leaderboard.json']
    current_games=read_json(args.current_output/'games.json')
    current_rows=rows_for(current_games)
    current_opening=read_json(args.current_output/'opening_trace.json')
    assert current_opening['snapshot']==SOURCE and len(current_rows)==12
    current_traces=current_opening['games']
    index=read_json(args.history_input/'index.json')
    metas=read_json(args.history_input/'artemis-index.json')
    assert len(metas)==16 and all(m in index for m in metas)
    assert {m['file'] for m in metas}=={m['file'] for m in index if any(s['id']==ARTEMIS for s in m['strategies'].values())}
    expected_replays={x['file']:x['sha256'] for x in read_json(args.history_input/'recovered-sha256.json')}
    games=[];traces=[]
    for meta in metas:
        assert all(meta['statuses'][s]=='DONE' for s in ('a','b'))
        data=(args.history_input/meta['file']).read_bytes()
        assert sha(data)==expected_replays[meta['file']]
        replay=json.loads(gzip.decompress(data))
        games.append(measure(meta,replay))
        traces.append(dict(opening(meta,replay),sha256=sha(data)))
    rows=rows_for(games);combined=rows+current_rows
    assert len(rows)==16
    historical_layouts={g['layout_sha256'] for g in games}
    current_layouts={g['layout_sha256'] for g,s,o in current_rows}
    assert len(historical_layouts)==16 and len(current_layouts)==12
    assert not historical_layouts & current_layouts
    assert not {g['match'] for g in games} & {g['match'] for g,s,o in current_rows}
    groups={
        'historical_16':rows,'current_12':current_rows,'same_id_combined_28':combined,
        'historical_vs_current_top6':[x for x in rows if x[2]['id'] in CURRENT_TOP6],
        'current_vs_current_top6':[x for x in current_rows if x[2]['id'] in CURRENT_TOP6],
        'same_id_combined_vs_current_top6':[x for x in combined if x[2]['id'] in CURRENT_TOP6],
    }
    descriptions=read_json(args.current_output/'metrics.json')['definitions']
    record=dict(historical_snapshot=HISTORY_SOURCE,historical_prepared_utc=provenance['snapshot_prepared_utc'],
                current_snapshot=SOURCE,strategy_id=ARTEMIS,
                limitation='Two separate time windows, same exact strategy ID. Combined rows are descriptive only, not a matched policy comparison; 16 older recovered games are not the full 34-row historical elite manifest.',
                current_top6_ids=sorted(CURRENT_TOP6),old_games=16,current_games=12,
                old_unique_layouts=16,current_unique_layouts=12,overlap_layouts=0,overlap_games=0,
                definitions=descriptions,sample_columns=SAMPLE_COLUMNS,
                opening={'historical':opening_counts(traces),'current':opening_counts(current_traces),
                         'same_id_combined':opening_counts(traces+current_traces)},
                groups={name:summary(group) for name,group in groups.items()},
                historical_per_game=[compact_game(row,trace) for row,trace in zip(rows,traces)])
    write_json(args.output/'history_metrics.json',record,compact=True)
    write_json(args.output/'history_opening_trace.json',dict(snapshot=HISTORY_SOURCE,
               definition=current_opening['definition'],games=traces))
    print(json.dumps({'opening':record['opening'],'groups':{k:dict(games=v['games'],wins=v['wins'],
          mean_margin=v['mean_margin'],tree_income=v['totals']['tree_income'],tree_turns=v['totals']['tree_turns'])
          for k,v in record['groups'].items()}},ensure_ascii=False,indent=2))
    if args.archive:
        print(json.dumps(pack_history(args.history_input,args.output,[g['file'] for g in games]),indent=2))


if __name__=='__main__':
    main()
