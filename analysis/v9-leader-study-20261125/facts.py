"""Summarize descriptive findings after explore.py; preserve opening actions verbatim."""
import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
from statistics import mean
from explore import SOURCE, validate_current_snapshot

ARTEMIS = '1f5b63b85d43a90ab4d4e75c294d1d62'
V8 = '52af7735a7677815efb48cdf94269e29'
V9 = '0f9896ed3dc3cd7bfad29fe2dd38d6fb'
SPONGE = '9245bbeea861f25b15439aa4d7e5a939'
RYAN = '0b7eaf8e37a0e0c5e658b0e315f9fbb3'


def net_tree(s):
    d = s['totals']
    return d.get('tree_income', 0) - d.get('plant_cost', 0) - d.get('seize_cost', 0)


def summary(rows):
    result = dict(games=len(rows), wins=sum(s['score'] > o['score'] for g,s,o in rows),
                  mean_margin=mean(s['score'] - o['score'] for g,s,o in rows),
                  matches=[g['match'] for g,s,o in rows], snapshots={}, totals={})
    for t in (25,30,50,75,100,150,200,225,250,280,299):
        x = [(s['samples'][str(t)], o['samples'][str(t)]) for g,s,o in rows if str(t) in s['samples']]
        result['snapshots'][str(t)] = {k:dict(own=mean(a[k] for a,b in x), opponent=mean(b[k] for a,b in x),
                                                 paired_difference=mean(a[k]-b[k] for a,b in x))
                                      for k in ('cash','collectors','planters','trees','cargo')}
    for k in ('tree_income','tree_turns','plants','seizes','plant_cost','seize_cost','recruit_cost',
              'non_tree_cash_inflow','terminal_cargo','disappeared_worker_cargo'):
        result['totals'][k] = dict(own=mean(s['totals'].get(k,0) for g,s,o in rows),
                                  opponent=mean(o['totals'].get(k,0) for g,s,o in rows),
                                  paired_difference=mean(s['totals'].get(k,0)-o['totals'].get(k,0) for g,s,o in rows))
    result['net_tree_cash_difference'] = mean(net_tree(s)-net_tree(o) for g,s,o in rows)
    result['positive_net_tree_difference_games'] = sum(net_tree(s)>net_tree(o) for g,s,o in rows)
    result['pooled_tree_income_per_owned_tree_turn'] = {
        'own':sum(s['totals']['tree_income'] for g,s,o in rows)/sum(s['totals']['tree_turns'] for g,s,o in rows),
        'opponent':sum(o['totals']['tree_income'] for g,s,o in rows)/sum(o['totals']['tree_turns'] for g,s,o in rows)}
    return result


def opening(meta, replay):
    steps=replay['steps'];base_players=steps[0][0]['observation']['players']
    seat=meta['order'].index(next(k for k,v in meta['strategies'].items() if v['id']==ARTEMIS))
    events=[]
    for side in (seat,1-seat):
        first=None
        for t in range(1,len(steps)):
            actions=steps[t][side]['action'] or {}
            if any(v in ('RECCOLLECTOR','RECPLANTER') for v in actions.values()):
                first=dict(replay_state=t,decision_observation_step=t-1,
                           base_actions=[dict(base_id=bid,position=pos,action=actions.get(bid))
                                         for bid,pos in sorted(base_players[side][1].items(),key=lambda p:p[1])])
                break
        events.append(first)
    traces=[]
    for t in range(1,4):
        sides=[]
        for side in (seat,1-seat):
            x=steps[t][side]
            sides.append(dict(seat=side,strategy=meta['strategies'][meta['order'][side]],
                              actions=x['action'],status=x.get('status'),info=x.get('info'),
                              remainingOverageTime=x.get('observation',{}).get('remainingOverageTime')))
        traces.append(dict(replay_state=t,decision_observation_step=t-1,sides=sides))
    return dict(match=meta['id'],game=meta['game'],file=meta['file'],artemis_seat=seat,
                opponent=meta['strategies'][meta['order'][1-seat]],
                first_recruit_artemis=events[0],first_recruit_opponent=events[1],first_three_steps=traces)


def main():
    p=argparse.ArgumentParser();p.add_argument('snapshot',type=Path);p.add_argument('output',type=Path)
    args=p.parse_args();games=json.loads((args.output/'games.json').read_text())
    validate_current_snapshot(args.snapshot)
    manifest=json.loads((args.output/'manifest.json').read_text())
    if manifest['snapshot']!=SOURCE:
        raise ValueError('games.json must first be regenerated by explore.py for the fixed current snapshot')
    index=json.loads((args.snapshot/'index.json').read_text())
    leaderboard=json.loads((args.snapshot/'leaderboard.json').read_text())['strategies']
    top6={s['id'] for s in leaderboard if s['rank']<=6}
    pairs={target:[(g,next(s for s in g['seats'] if s['id']==target),next(s for s in g['seats'] if s['id']!=target))
                   for g in games if any(s['id']==target for s in g['seats'])]
           for target in (ARTEMIS,V8,V9)}
    groups={'artemis_all':pairs[ARTEMIS], 'v8_all':pairs[V8], 'v9_all':pairs[V9],
            'v9_vs_top6':[x for x in pairs[V9] if x[2]['id'] in top6],
            'artemis_vs_sponge_v5':[x for x in pairs[ARTEMIS] if x[2]['id']==SPONGE],
            'v9_vs_sponge_v5':[x for x in pairs[V9] if x[2]['id']==SPONGE],
            'artemis_vs_ryan_1660k':[x for x in pairs[ARTEMIS] if x[2]['id']==RYAN],
            'v9_vs_ryan_1660k':[x for x in pairs[V9] if x[2]['id']==RYAN]}
    observations=[]
    for meta in index:
        if not any(s['id']==ARTEMIS for s in meta['strategies'].values()):continue
        data=(args.snapshot/meta['file']).read_bytes();record=opening(meta,json.loads(gzip.decompress(data)))
        record['sha256']=hashlib.sha256(data).hexdigest();observations.append(record)
    opening_report=dict(snapshot='ddc3e6f6922474ad5894a8066be5b906bf35af55',
        definition='Replay state t contains actions chosen from observation t-1. Bases ordered by ascending physical position. Empty actions do not establish intent.', games=observations)
    (args.output/'opening_trace.json').write_text(json.dumps(opening_report,ensure_ascii=False,indent=2)+'\n')
    by_opening={}
    for row in observations:
        acts=row['first_three_steps'][0]['sides'][1]['actions'] or {}
        label=''.join(sorted('C' if x=='RECCOLLECTOR' else 'P' for x in acts.values() if x in ('RECCOLLECTOR','RECPLANTER'))) or 'none'
        by_opening.setdefault(label,[]).append(next(x for x in pairs[ARTEMIS] if x[0]['match']==row['match']))
    cases=[]
    for match in ('d9bbe30417b7ed41fe67b00d0a125a8d','a5ff9b8020bc4047ba7beeb7a426c6d2','a874c911b9f703ec98b00f713f7b4f54'):
        g=next(g for g in games if g['match']==match);sid=V9 if any(s['id']==V9 for s in g['seats']) else ARTEMIS
        s=next(s for s in g['seats'] if s['id']==sid);o=next(s for s in g['seats'] if s['id']!=sid)
        stages={}
        for t in (100,150,200,225,250,280,299):
            a,b=s['samples'][str(t)],o['samples'][str(t)]
            stages[str(t)]=dict(cash_difference=a['cash']-b['cash'],cargo_difference=a['cargo']-b['cargo'],
                               cash_plus_cargo_difference=a['cash']+a['cargo']-b['cash']-b['cargo'],own_trees=a['trees'],opponent_trees=b['trees'])
        cases.append(dict(match=match,seed=g['seed'],target=s['name'],seat=s['seat'],opponent=o['name'],margin=s['score']-o['score'],stages=stages))
    findings=dict(snapshot='ddc3e6f6922474ad5894a8066be5b906bf35af55',games=len(games),unique_layouts=len({g['layout_sha256'] for g in games}),
        definitions={
            'tree_turns':'Sum of owned living tree counts over replay states 1..terminal; directly observed.',
            'tree_income':'Sum of current-frame obs.trees[tree_id][1] over current owner trees; recorded tree absorption income, excludes collision cash paid directly to a tree owner.',
            'plant_cost':'Current turn price fixed from previous state living global tree count per Board.next; same-turn plantings use the same price.',
            'recruit_cost':'Successful base commands simulated in base order from previous cash/population, before movement/collision; includes recruits dying in the same turn; all increment-cost settings checked as zero.',
            'net_tree_cash_difference':'Recorded tree absorption minus planting and seizing costs, own minus opponent. Descriptive accounting category, not counterfactual investment value.',
            'non_tree_cash_inflow':'Residual: cash change plus recruitment/planting/seizing costs minus recorded tree absorption. Includes deposits, collision cash (including tree-cell collisions), and rounding; NOT a direct deposit measurement.',
            'disappeared_worker_cargo':'Cargo before worker disappears; may be recovered by friendly collision or paid to a tree/base; NOT net economic loss.',
            'cash_plus_cargo':'Cash plus currently carried cargo; excludes future tree income, worker value, transport risk, and costs; not a complete state valuation.',
            'comparison':'Each own/opponent difference is paired within the same game; comparing Artemis group and v9 group against a common opponent still uses different unpaired maps.'},
        groups={key:summary(rows) for key,rows in groups.items()},
        artemis_grouped_by_opponent_initial_recruitment={key:summary(rows) for key,rows in by_opening.items()},
        artemis_first_recruit_state_counts=dict(Counter(str(x['first_recruit_artemis']['replay_state']) for x in observations)),
        cases=cases)
    (args.output/'key_findings.json').write_text(json.dumps(findings,ensure_ascii=False,indent=2)+'\n')
    compact_groups={}
    for name,data in findings['groups'].items():
        compact_groups[name]={k:v for k,v in data.items() if k not in ('snapshots','matches')}
        compact_groups[name]['snapshots']={t:{k:round(v['paired_difference'],6) for k,v in cols.items()} for t,cols in data['snapshots'].items()}
    compact_games=[]
    for g in games:
        target=next(s for s in g['seats'] if s['id'] in (ARTEMIS,V8,V9))
        opponent=next(s for s in g['seats'] if s['id']!=target['id'])
        cols={}
        for t in (25,30,50,75,100,150,200,225,250,280,299):
            a,b=target['samples'][str(t)],opponent['samples'][str(t)]
            cols[str(t)]=[a['cash'],b['cash'],round(a['cargo'],6),round(b['cargo'],6),a['trees'],b['trees'],a['collectors'],b['collectors'],a['planters'],b['planters']]
        compact_games.append(dict(match=g['match'],game=g['game'],file=g['file'],seed=g['seed'],layout_sha256=g['layout_sha256'],target=target['id'],opponent=opponent['id'],seat=target['seat'],margin=target['score']-opponent['score'],net_tree_difference=net_tree(target)-net_tree(opponent),samples=cols))
    compact=dict(snapshot=findings['snapshot'],definitions=findings['definitions'],games=findings['games'],unique_layouts=findings['unique_layouts'],
        sample_columns=['own_cash','opponent_cash','own_cargo','opponent_cargo','own_trees','opponent_trees','own_collectors','opponent_collectors','own_planters','opponent_planters'],
        group_snapshots='paired own-minus-opponent differences; group totals retain both means',groups=compact_groups,
        opening_counts=findings['artemis_first_recruit_state_counts'],
        opening_groups={k:{'games':v['games'],'wins':v['wins'],'turn30':v['snapshots']['30'],'turn75':v['snapshots']['75']} for k,v in findings['artemis_grouped_by_opponent_initial_recruitment'].items()},
        cases=findings['cases'],per_game=compact_games)
    (args.output/'metrics.json').write_text(json.dumps(compact,ensure_ascii=False,separators=(',',':'))+'\n')
    print('Wrote opening_trace.json, key_findings.json, and metrics.json')

if __name__=='__main__':main()
